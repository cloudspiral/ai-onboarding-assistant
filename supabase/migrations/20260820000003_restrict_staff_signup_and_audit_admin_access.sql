  created_at timestamp(6) without time zone not null default now(),
  updated_at timestamp(6) without time zone not null default now()
);
create index if not exists index_admin_access_audits_on_actor_digest
  on public.admin_access_audits(actor_digest);
create index if not exists index_admin_access_audits_on_action_and_created_at
  on public.admin_access_audits(action, created_at);

alter table public.admin_access_audits enable row level security;
revoke all on table public.admin_access_audits from anon, authenticated;

