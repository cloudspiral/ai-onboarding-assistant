-- Permit public anonymous onboarding while keeping permanent staff identities
-- pre-provisioned. Existing staff sign-ins do not invoke this creation hook.
create or replace function public.hook_restrict_staff_signup(event jsonb)
returns jsonb
language plpgsql
set search_path = ''
as $$
begin
  if coalesce((event->'user'->>'is_anonymous')::boolean, false) then
    return '{}'::jsonb;
  end if;

  return jsonb_build_object(
    'error', jsonb_build_object(
      'http_code', 403,
      'message', 'Staff accounts are provisioned by an administrator.'
    )
  );
end;
$$;

grant usage on schema public to supabase_auth_admin;
grant execute on function public.hook_restrict_staff_signup(jsonb) to supabase_auth_admin;
revoke execute on function public.hook_restrict_staff_signup(jsonb) from anon, authenticated, public;

